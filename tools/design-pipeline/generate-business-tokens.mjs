#!/usr/bin/env node
// Momentra Business v3 design token generator
// Generates Business tokens for Android (Kotlin) and iOS (Swift) from design/tokens/business.tokens.json
// Usage: node generate-business-tokens.mjs [--check]

import path from 'node:path';
import { PATHS, Plan, readJson, camel, pascal, snake, parseColor, argbHex, rgbHex, fmt } from './lib.mjs';

const check = process.argv.includes('--check');
const tokens = readJson(PATHS.businessTokens);
const plan = new Plan({ check });

const SRC_TOKENS = 'design/tokens/business.tokens.json';
const banner = (c, src) => `${c} GENERATED by tools/design-pipeline/generate-business-tokens.mjs from ${src}.\n${c} DO NOT EDIT: change the source JSON and run \`npm run business-tokens\` in tools/design-pipeline.\n`;

// Token model
function flatten(node, prefix = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (k.startsWith('$')) continue;
    if (v && typeof v === 'object' && '$value' in v) out.push({ path: [...prefix, k], type: v.$type, raw: v.$value, ext: v.$extensions });
    else if (v && typeof v === 'object') flatten(v, [...prefix, k], out);
  }
  return out;
}
const all = flatten(tokens);
const byPath = new Map(all.map((t) => [t.path.join('.'), t]));

function resolve(value, seen = []) {
  if (typeof value === 'string') {
    const m = /^\{([^}]+)\}$/.exec(value);
    if (m) {
      if (seen.includes(m[1])) throw new Error(`Alias cycle: ${[...seen, m[1]].join(' -> ')}`);
      const t = byPath.get(m[1]);
      if (!t) throw new Error(`Unknown alias {${m[1]}}`);
      return resolve(t.raw, [...seen, m[1]]);
    }
  }
  return value;
}
for (const t of all) { t.value = resolve(t.raw); t.alias = typeof t.raw === 'string' && t.raw.startsWith('{') ? t.raw.slice(1, -1) : null; }

const group = (g) => all.filter((t) => t.path[0] === g);

// Colors
const colors = group('color').map((t) => {
  const sub = t.path.slice(1);
  return { ...t, sub, c: parseColor(t.value), swift: camel(sub), kt: pascal(sub) };
});

// Dimensions
const dims = (g) => group(g).map((t) => ({ ...t, swift: camel(t.path.slice(1)), kt: pascal(t.path.slice(1)) }));
const radius = dims('radius');
const space = dims('space');
const size = dims('size');

// Typography
const faces = Object.fromEntries(group('font').filter((t) => t.path[1] === 'face').map((t) => [Number(t.path[2]), t.value]));
const type = group('typography').map((t) => {
  const v = t.value;
  const face = faces[v.fontWeight];
  if (!face) throw new Error(`No font face for weight ${v.fontWeight} (${t.path.join('.')})`);
  return { ...t, v, face, swift: camel(t.path.slice(1)), kt: pascal(t.path.slice(1)) };
});

// Domain mapping from tokens
const domainInfo = tokens.$extensions?.momentra?.domains || {};
const domains = Object.entries(domainInfo).map(([key, info]) => ({
  key,
  label: info.label,
  swift: info.swift,
  kotlin: info.kotlin,
}));

// Helper functions
const camelCase = (parts) => parts.flatMap((p) => String(p).split(/[^A-Za-z0-9]+/)).filter(Boolean).map((w, i) => i === 0 ? w[0].toLowerCase() + w.slice(1) : w[0].toUpperCase() + w.slice(1)).join('');
const pascalCase = (parts) => { const c = camelCase(parts); return c[0].toUpperCase() + c.slice(1); };
const ktFloat = (n) => { const s = fmt(n, 3); return s.includes('.') ? s : `${s}.0`; };

// iOS Swift Business Tokens
{
  const L = [];
  L.push(banner('//', SRC_TOKENS));
  L.push('// Momentra Business v3 design tokens. Domain-aware theming.');
  L.push('// DO NOT EDIT: generated file');
  L.push('');
  L.push('import SwiftUI');
  L.push('');
  L.push('enum BusinessDomain: String, CaseIterable {');
  for (const d of domains) {
    L.push(`    case ${d.swift} = "${d.key}"`);
  }
  L.push('    static var fallback: BusinessDomain { .corporate }');
  L.push('}');
  L.push('');
  L.push('enum BusinessTokens {');
  L.push('    enum Colors {');

  // Neutral colors
  const neutralColors = colors.filter(c => !c.sub.includes('domain'));
  for (const c of neutralColors) {
    L.push(`        static let ${c.swift} = Color(hex: "${rgbHex(c.c)}")`);
  }

  L.push('');
  L.push('        // Domain color palettes');
  for (const d of domains) {
    const domainColors = colors.filter(c => c.sub[0] === 'domain' && c.sub[1] === d.key);
    for (const c of domainColors) {
      const constName = `${d.swift}${pascalCase(c.sub.slice(2))}`;
      L.push(`        static let ${constName} = Color(hex: "${rgbHex(c.c)}")`);
    }
  }

  L.push('');
  L.push('        static func accent(for domain: BusinessDomain) -> Color {');
  L.push('            switch domain {');
  for (const d of domains) {
    L.push(`            case .${d.swift}: return ${d.swift}Accent`);
  }
  L.push('            }');
  L.push('        }');
  L.push('');
  L.push('        static func domainColors(for domain: BusinessDomain) -> [String: Color] {');
  L.push('            var colors: [String: Color] = [:]');
  for (const d of domains) {
    const domainColors = colors.filter(c => c.sub[0] === 'domain' && c.sub[1] === d.key);
    for (const c of domainColors) {
      const colorName = c.sub.slice(2).join('');
      L.push(`            colors["${d.key}.${colorName}"] = ${d.swift}${pascalCase(c.sub.slice(2))}`);
    }
  }
  L.push('            return colors');
  L.push('        }');
  L.push('    }');

  // Dimensions
  for (const [name, list] of [['Radius', radius], ['Space', space], ['Size', size]]) {
    L.push('', `    enum ${name} {`);
    for (const d of list) {
      L.push(`        static let ${d.swift}: CGFloat = ${fmt(d.value)}`);
    }
    L.push('    }');
  }

  // Typography
  L.push('', '    enum Typography {');
  for (const t of type) {
    L.push(`        static let ${t.swift} = BusinessTextStyle(size: ${fmt(t.v.fontSize)}, lineHeight: ${fmt(t.v.lineHeight)}, weight: ${t.v.fontWeight})`);
  }
  L.push('    }');

  L.push('}');
  L.push('');
  L.push('struct BusinessTextStyle {');
  L.push('    let size: CGFloat');
  L.push('    let lineHeight: CGFloat');
  L.push('    let weight: Int');
  L.push('    var font: Font {');
  L.push('        let wf: Font.Weight');
  L.push('        switch weight {');
  L.push('        case 400: wf = .regular');
  L.push('        case 500: wf = .medium');
  L.push('        case 600: wf = .semibold');
  L.push('        case 700: wf = .bold');
  L.push('        case 800: wf = .heavy');
  L.push('        default: wf = .regular');
  L.push('        }');
  L.push('        return Font.custom("PlusJakartaSans", size: size).weight(wf)');
  L.push('    }');
  L.push('}');

  plan.text(path.join(PATHS.iosGenerated, 'BusinessTokens.generated.swift'), L.join('\n') + '\n');
}

// Android Kotlin Business Tokens
{
  const L = [];
  L.push(banner('//', SRC_TOKENS));
  L.push('// Momentra Business v3 design tokens. Domain-aware theming.');
  L.push('// DO NOT EDIT: generated file');
  L.push('');
  L.push('package com.example.momentra.ui.theme.generated');
  L.push('');
  L.push('import androidx.compose.ui.graphics.Color');
  L.push('import androidx.compose.ui.unit.dp');
  L.push('import androidx.compose.ui.unit.sp');
  L.push('');
  L.push('enum class BusinessDomain(val value: String) {');
  for (const [i, d] of domains.entries()) {
    L.push(`    ${d.kotlin}("${d.key}")${i < domains.length - 1 ? ',' : ';'}`);
  }
  L.push('}');
  L.push('');
  L.push('object BusinessTokens {');
  L.push('    object Colors {');

  // Neutral colors
  const neutralColors = colors.filter(c => !c.sub.includes('domain'));
  for (const c of neutralColors) {
    L.push(`        val ${c.kt} = Color(${argbHex(c.c)})`);
  }

  L.push('');
  L.push('        // Domain accent colors');
  for (const d of domains) {
    const domainAccent = colors.find(c => c.sub.join('.') === `domain.${d.key}.accent`);
    if (domainAccent) {
      L.push(`        val ${d.kotlin}Accent = Color(${argbHex(domainAccent.c)})`);
    }
  }

  L.push('');
  L.push('        fun accent(domain: BusinessDomain): Color = when(domain) {');
  for (const d of domains) {
    L.push(`            BusinessDomain.${d.kotlin} -> ${d.kotlin}Accent`);
  }
  L.push(`            else -> ${domains[0].kotlin}Accent`);
  L.push('        }');
  L.push('    }');

  // Dimensions
  for (const [name, list] of [['Radius', radius], ['Space', space], ['Size', size]]) {
    L.push('', `    object ${name} {`);
    for (const d of list) {
      L.push(`        val ${d.kt} = ${ktFloat(d.value)}.dp`);
    }
    L.push('    }');
  }

  L.push('');
  L.push('    object Type {');
  for (const t of type) {
    L.push(`        val ${t.kt} = ${ktFloat(t.v.fontSize)}f.sp`);
  }
  L.push('    }');

  L.push('}');
  L.push('');
  L.push('// Empty screen tokens for Business - domain aware');
  L.push('data class BusinessEmptyTokens(val domain: BusinessDomain) {');
  L.push('    val accent = BusinessTokens.Colors.accent(domain)');
  L.push('    val textPrimary = BusinessTokens.Colors.TextPrimary');
  L.push('    val textSecondary = BusinessTokens.Colors.TextSecondary');
  L.push('    val textMuted = BusinessTokens.Colors.TextMuted');
  L.push('    val cardFill = Color.White.copy(alpha = 0.08f)');
  L.push('    val cardStroke = Color.White.copy(alpha = 0.10f)');
  L.push('    val iconWell = accent.copy(alpha = 0.10f)');
  L.push('}');

  plan.text(path.join(PATHS.androidGenerated, 'BusinessTokens.kt'), L.join('\n') + '\n');
}

plan.apply();
process.exit(plan.report(check ? 'business-tokens:check' : 'business-tokens'));